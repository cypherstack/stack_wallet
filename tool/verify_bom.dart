// Checks the local toolchain and the pinned native plugins against
// stack-bom.toml.
//
//   dart tool/verify_bom.dart            check, exit 1 on a mismatch
//   dart tool/verify_bom.dart --toolchains  check only the installed toolchain
//   dart tool/verify_bom.dart --plugins     check only the pubspec.lock pins
//   dart tool/verify_bom.dart --update   refresh an existing [plugins] section from pubspec.lock
//
// No packages needed, so it runs before `flutter pub get`.
//
// CI splits the two: the toolchain check runs on the host runner before the
// prebuilt image is used, because the image's toolchain is frozen until it is
// rebuilt. Raising a minimum (flutter_min / go_min) must therefore fail the
// runner step, not only the in-image step.
import 'dart:convert';
import 'dart:io';

import 'bom_parser.dart';

int _failures = 0;
int _warnings = 0;

void _ok(String m) => stdout.writeln('[OK]   $m');
void _warn(String m) {
  _warnings++;
  stdout.writeln('[WARN] $m');
}

void _fail(String m) {
  _failures++;
  stdout.writeln('[FAIL] $m');
}

Future<String?> _run(String exe, List<String> args) async {
  try {
    // runInShell lets Windows start flutter.bat. Only stdout is parsed: Flutter
    // writes startup-lock warnings to stderr, and appending those to the JSON
    // breaks --machine output.
    final r = await Process.run(exe, args, runInShell: Platform.isWindows);
    if (r.exitCode != 0) return null;
    return '${r.stdout}'.trim();
  } on ProcessException {
    return null;
  }
}

Future<void> _update() async {
  final Map<String, String> existingPlugins;
  try {
    final raw = File(bomFileName).readAsStringSync();
    existingPlugins = readBom(raw)['plugins'] ?? {};
  } on FormatException catch (e) {
    stderr.writeln(e.message);
    exit(2);
  }
  if (existingPlugins.isEmpty) {
    stderr.writeln(
      'Plugin pins are not stored in $bomFileName; pubspec.lock pins them. '
      'Run flutter pub get instead.',
    );
    exit(2);
  }
  final refs = lockRefs();
  if (refs.isEmpty) {
    stderr.writeln('pubspec.lock not found or has none of the plugins.');
    exit(2);
  }
  final text = File(bomFileName).readAsStringSync();
  try {
    requireSinglePluginsSection(text);
  } on FormatException catch (e) {
    stderr.writeln(e.message);
    exit(2);
  }
  Map<String, String> existing;
  try {
    existing = readBom(text)['plugins'] ?? {};
  } on FormatException catch (e) {
    stderr.writeln(e.message);
    exit(2);
  }
  // Plugin pins live in pubspec.lock now. Refresh an existing table for older
  // branches, but never create one in a BOM that does not carry it.
  if (existing.isEmpty && !RegExp(r'\[plugins\]').hasMatch(text)) {
    stdout.writeln('No [plugins] table in $bomFileName; nothing to update.');
    return;
  }
  final declared = declaredPlugins();
  // Without a pubspec.yaml we cannot tell which app is configured; keep the
  // old behaviour and update every plugin the lock knows about.
  final updateable = declared.isEmpty ? bomPluginNames.toSet() : declared;
  final header =
      RegExp(r'^\[plugins\][ \t]*(#.*)?$', multiLine: true).firstMatch(text);
  final start = header?.start ?? -1;
  if (start < 0 && RegExp(r'\[plugins\]').hasMatch(text)) {
    stderr.writeln(
      'Found [plugins] outside a table header; refusing to update',
    );
    exit(2);
  }
  final tailStart = start < 0
      ? text.length
      : text.indexOf(RegExp(r'\n\[', multiLine: true), start + 1);
  final tail = tailStart < 0 ? '' : text.substring(tailStart);
  final head = start < 0
      ? text.trimRight()
      : text.substring(0, start).trimRight();
  for (final n in updateable) {
    if (!refs.containsKey(n)) {
      stderr.writeln(
        'Warning: $n is declared but missing from pubspec.lock; '
        'pin not updated',
      );
    }
  }
  final buf = StringBuffer(head)
    ..writeln('\n')
    ..writeln('[plugins]')
    ..writeln(
      '# Generated by `dart tool/verify_bom.dart --update` from pubspec.lock. Do not edit by hand.',
    );
  var refreshed = 0;
  var preserved = 0;
  for (final n in bomPluginNames) {
    if (updateable.contains(n) && refs.containsKey(n)) {
      buf.writeln('$n = "${refs[n]}"');
      refreshed++;
    } else if (existing.containsKey(n)) {
      // Keep pins for apps this checkout is not configured for.
      buf.writeln('$n = "${existing[n]}"');
      preserved++;
    }
  }
  for (final entry in existing.entries) {
    if (bomPluginNames.contains(entry.key)) continue;
    buf.writeln('${entry.key} = "${entry.value}"');
    preserved++;
  }
  buf.write(tail);
  File(bomFileName).writeAsStringSync(buf.toString());
  stdout.writeln(
    'Updated [plugins] in $bomFileName '
    '($refreshed refreshed, $preserved preserved).',
  );
}

Never _finish() {
  stdout.writeln('\n$_failures failure(s), $_warnings warning(s).');
  exit(_failures == 0 ? 0 : 1);
}

void _checkPlugins(Map<String, Map<String, String>> bom) {
  final refs = lockRefs();
  final pinned = bom['plugins'] ?? {};
  // Plugin pins are no longer stored in the BOM; pubspec.lock is the source of
  // truth. Keep the parser for older branches that still carry a
  // [plugins] table.
  if (pinned.isEmpty) return;
  final declared = declaredPlugins();
  final pubspecExists = File('pubspec.yaml').existsSync();
  // A fresh checkout has no pubspec.yaml: build_app.sh generates it later.
  // In that case check every plugin the lock contains, as before.
  final required = pubspecExists ? declared : bomPluginNames.toSet();
  if (refs.isEmpty) {
    _warn('pubspec.lock not found, plugin pins not checked');
  } else if (required.isEmpty) {
    _fail(
      'could not read plugin declarations from pubspec.yaml '
      '(expected them under dependencies: or dependency_overrides:)',
    );
  } else {
    for (final n in bomPluginNames) {
      if (!required.contains(n)) continue;
      final ref = refs[n];
      final pin = pinned[n];
      if (ref == null) {
        _fail(
          '$n is missing from pubspec.lock (path dependency or not resolved)',
        );
      } else if (pin == null) {
        _fail('$n is missing from [plugins] in $bomFileName (run --update)');
      } else if (pin == ref) {
        _ok('$n ${shortVersion(ref)}');
      } else {
        _fail(
          '$n is ${shortVersion(ref)} in pubspec.lock but '
          '${shortVersion(pin)} in $bomFileName (run --update)',
        );
      }
    }
  }
}

Future<void> main(List<String> args) async {
  if (!File(bomFileName).existsSync()) {
    stderr.writeln('Run from the repository root ($bomFileName not found).');
    exit(2);
  }
  if (args.contains('--update')) return _update();

  final bomText = File(bomFileName).readAsStringSync();
  Map<String, Map<String, String>> bom;
  try {
    requireSinglePluginsSection(bomText);
    bom = readBom(bomText);
  } on FormatException catch (e) {
    stderr.writeln(e.message);
    exit(2);
  }
  final root = bom[''] ?? {};
  if (root['schema_version'] != '1') {
    _fail('schema_version must be 1 in $bomFileName');
  }
  if (args.contains('--plugins')) {
    _checkPlugins(bom);
    _finish();
  }
  final toolchainsOnly = args.contains('--toolchains');
  final tc = bom['toolchain'] ?? {};

  // Flutter / Dart
  final configuredFlutter = Platform.environment['FLUTTER']?.trim() ?? '';
  final flutterExe =
      configuredFlutter.isNotEmpty && File(configuredFlutter).existsSync()
      ? configuredFlutter
      : resolveOnPath('flutter');
  // A Flutter/Dart executable found on PATH under a directory with a space in
  // its name breaks the native-assets hooks and the .dart_tool config writers,
  // which do not quote paths. Catch it here with a clear error rather than
  // failing deep inside a build with a cryptic "No such file or directory".
  if (flutterExe.contains(' ')) {
    _fail(
      'Flutter is resolved to "$flutterExe": a path with a space in a name '
      'breaks the build. Move the Flutter checkout to a path with no spaces, '
      'or set FLUTTER=/path/to/flutter/bin/flutter to an unspaced location.',
    );
    _finish();
  }
  final fl = await _run(flutterExe, ['--version', '--machine']);
  if (fl == null) {
    // In CI the --toolchains check runs on the host runner before the
    // prebuilt image is used; the runner has no Flutter (the image does),
    // so a missing Flutter is a warning there, not a failure. A plain run
    // (local or in-image) still requires it.
    if (toolchainsOnly) {
      _warn('flutter not found in PATH (expected inside the CI image)');
    } else {
      _fail('flutter not found in PATH');
    }
  } else {
    final start = fl.indexOf('{');
    final end = fl.lastIndexOf('}');
    if (start < 0 || end <= start) {
      _fail('unexpected output from flutter --version --machine');
    } else {
      try {
        final info =
            jsonDecode(fl.substring(start, end + 1)) as Map<String, dynamic>;
        final v = info['frameworkVersion'] as String;
        final d = info['dartSdkVersion'] as String;
        if (compareVersions(v, tc['flutter_min'] ?? '0') < 0) {
          _fail('Flutter $v is older than the minimum ${tc['flutter_min']}');
        } else if (v != tc['flutter']) {
          _warn(
            'Flutter $v (recommended ${tc['flutter']}, '
            'minimum ${tc['flutter_min']})',
          );
        } else {
          _ok('Flutter $v');
        }
        final prefix = tc['dart_prefix'] ?? '';
        if (prefix.isEmpty) {
          _fail('dart_prefix is missing from $bomFileName');
        } else if (d.startsWith('$prefix.')) {
          _ok('Dart $d');
        } else {
          _fail('Dart $d does not match $prefix.x');
        }
      } on FormatException {
        _fail('could not parse flutter --version --machine output');
      }
    }
  }

  // Rust
  final list = await _run('rustup', ['toolchain', 'list']);
  final rust = tc['rust'] ?? '';
  if (list == null) {
    // On the CI host runner (pre-image) rustup is not installed — the pinned
    // toolchains live in the prebuilt image. A missing rustup is a warning
    // there, not a failure. A plain run (local or in-image) still requires it.
    if (toolchainsOnly) {
      _warn('rustup not found in PATH (expected inside the CI image)');
    } else {
      _fail('rustup not found in PATH');
    }
  } else if (list.split('\n').any((l) => l.startsWith('$rust-'))) {
    _ok('Rust $rust installed via rustup');
  } else if (toolchainsOnly) {
    // rustup is present but the pinned toolchain is not installed. On the CI
    // host runner the pinned toolchains live in the prebuilt image, not in the
    // runner's rustup, so a present-but-missing toolchain is a warning there,
    // not a failure. A plain run (local or in-image) still requires it.
    _warn("Rust $rust not installed via rustup (expected inside the CI image)");
  } else {
    _fail('Rust $rust is not installed (rustup toolchain install $rust)');
  }
  final dnssec = tc['dnssec_rust'] ?? '';
  if (dnssec.isEmpty) {
    _fail('dnssec_rust is missing from $bomFileName');
  } else if (list == null) {
    // rustup absent: already reported above (fail locally, warn on the runner).
    if (toolchainsOnly) {
      _warn('DNSSEC Rust $dnssec not checked (rustup absent; in the CI image)');
    }
  } else if (list.split('\n').any((l) => l.startsWith('$dnssec-'))) {
    _ok('DNSSEC Rust $dnssec installed via rustup');
  } else if (toolchainsOnly) {
    // Same as the Rust check above: the pinned DNSSEC toolchain lives in the
    // prebuilt image, not the host runner's rustup, so warn rather than fail.
    _warn(
      "DNSSEC Rust $dnssec not installed via rustup (expected in the CI image)",
    );
  } else {
    _fail(
      'DNSSEC Rust $dnssec is not installed '
      '(rustup toolchain install $dnssec)',
    );
  }

  // Go
  final go = await _run('go', ['version']);
  final gm = go == null ? null : RegExp(r'go(\d+\.\d+(\.\d+)?)').firstMatch(go);
  if (gm == null) {
    _warn('go not found in PATH; only apps that build Go components need it');
  } else if (compareVersions(gm.group(1)!, tc['go_min'] ?? '0') < 0) {
    _fail('Go ${gm.group(1)} is older than the minimum ${tc['go_min']}');
  } else {
    _ok('Go ${gm.group(1)}');
  }

  // Xcode (macOS only)
  if (Platform.isMacOS) {
    final mac = bom['macos'] ?? {};
    final xc = await _run('xcodebuild', ['-version']);
    final xm = xc == null ? null : RegExp(r'Xcode (\S+)').firstMatch(xc);
    if (xm == null) {
      _fail('Xcode not found (xcode-select -p)');
    } else if (xm.group(1) == mac['xcode']) {
      _ok('Xcode ${xm.group(1)}');
    } else if (xm.group(1) == mac['xcode_dnix']) {
      _warn(
        'Xcode ${xm.group(1)} is the version dnix pins; '
        '${mac['xcode']} is recommended for app builds',
      );
    } else {
      _warn('Xcode ${xm.group(1)} (recommended ${mac['xcode']})');
    }
  }

  if (!toolchainsOnly) _checkPlugins(bom);
  _finish();
}
