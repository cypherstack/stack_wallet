import 'package:flutter_test/flutter_test.dart';
import 'package:stackwallet/wallets/wallet/supporting/owned_input_signatures.dart';

// Real transactions as served by each coin's ElectrumX server. The parent
// binding reads parents on every ElectrumX coin, and a rejected parent fails
// the whole UTXO refresh, so each layout the parser meets is covered here.

void main() {
  test("Dash special transactions end with an extra payload", () {
    final tx = parseAuthenticatedTransaction(
      txid: _dashCoinbaseTxid,
      rawTxHex: _dashCoinbaseHex,
    );
    expect(tx.outputs.map((e) => e.value.toInt()), [51326352, 153979055]);
  });

  test("Firo Spark spends end with an extra payload", () {
    final tx = parseAuthenticatedTransaction(
      txid: _firoSparkSpendTxid,
      rawTxHex: _firoSparkSpendHex,
    );
    expect(tx.outputs.map((e) => e.value.toInt()), [36215612963, 0]);
  });

  test("Peercoin transactions before version 3 carry a timestamp", () {
    expect(
      () => parseAuthenticatedTransaction(
        txid: _peercoinV1Txid,
        rawTxHex: _peercoinV1Hex,
      ),
      throwsA(isA<UnauthenticatedTransaction>()),
    );
    final tx = parseAuthenticatedTransaction(
      txid: _peercoinV1Txid,
      rawTxHex: _peercoinV1Hex,
      legacyTimestamp: true,
    );
    expect(tx.outputs.map((e) => e.value.toInt()), [31193356, 36000000]);
  });

  test("Peercoin version 3 witness transactions have no timestamp", () {
    final tx = parseAuthenticatedTransaction(
      txid: _peercoinV3Txid,
      rawTxHex: _peercoinV3Hex,
      legacyTimestamp: true,
    );
    expect(tx.inputs.length, 1);
    expect(tx.outputs.length, 2);
  });
}

